"""ngspice runner: device-model verification and half-bridge commutation testbench.

Testbench (hard turn-on of the high-side switch in a synchronous buck, i.e. the
event that produces the switch-node overshoot reported by EPC WP010):

   VIN --Lbulk-- Cbulk ---+--- Cin_hf(ESR) ---+
                          |                    |
                         (bulk)            Lloop/Rloop (power-loop, from extraction)
                                               |
                                            HS drain ... HS source = SW ... SR drain
                                                                   SR source = GND(Cin-)
   SW --> I_load (20 A, ideal: output inductor current is constant over ns)

Sequence: SR on (freewheeling) -> SR gate off at t1 -> dead time -> HS gate on
at t2 -> commutation -> SW overshoot & ringing.  The overshoot is measured as
in EPC WP010: (V_SW,peak - VIN)/VIN, SW measured at the SR (GND reference
across SR, i.e. at the device).
"""
from __future__ import annotations

import os
import subprocess
import tempfile
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

import epc_model

ROOT = Path(__file__).resolve().parents[1]
NGSPICE = Path(os.environ.get("NGSPICE", ROOT / "tools" / "ngspice_dl" / "Spice64" / "bin" / "ngspice_con.exe"))


def run_deck(deck: str, workdir: Path | None = None, timeout=600) -> dict[str, np.ndarray]:
    """Run an ngspice deck in batch mode; the deck must `wrdata out.txt ...`."""
    wd = Path(workdir or tempfile.mkdtemp(prefix="ngs_"))
    wd.mkdir(parents=True, exist_ok=True)
    (wd / "deck.cir").write_text(deck)
    p = subprocess.run([str(NGSPICE), "-b", "deck.cir"], cwd=wd, capture_output=True, text=True, timeout=timeout)
    (wd / "ngspice.log").write_text(p.stdout + "\n--- stderr ---\n" + p.stderr)
    out = wd / "out.txt"
    if not out.exists():
        raise RuntimeError(f"ngspice produced no output in {wd}; see ngspice.log")
    raw = np.loadtxt(out, ndmin=2)
    return {"raw": raw, "log": p.stdout}


@dataclass
class Bench:
    vin: float = 12.0
    iload: float = 20.0
    L_loop: float = 0.4e-9        # total HF power-loop inductance (H)
    R_loop: float = 2e-3          # copper loop resistance at ring frequency (ohm)
    esr_cin: float = 1.5e-3       # equivalent ESR of the HF Cin bank (ohm)
    C_cin: float = 2.0e-6         # HF Cin bank capacitance (F)
    L_bulk: float = 10e-9
    C_bulk: float = 100e-6
    r_pullup: float = 2.7         # gate driver pull-up (ohm)   [assumption, LM5113-class]
    r_pulldown: float = 0.5       # gate driver pull-down (ohm) [assumption]
    L_gate: float = 1.0e-9        # gate loop inductance (H)    [assumption]
    v_drive: float = 5.0
    t_rise_drv: float = 1e-9      # driver output edge (s)
    dead: float = 10e-9           # dead time SR-off -> HS-on (s)
    coss_scale: float = 1.0
    t_stop: float = 80e-9
    t_step: float = 2e-12
    # --- Phase 3/6 extensions (defaults reproduce the original bench exactly)
    device: str = "EPC2015C"
    L_gate_hs: float | None = None  # per-gate loop inductance (H); None -> L_gate
    L_gate_ls: float | None = None
    k_p_hs: float = 0.0           # coupling coefficient power loop <-> HS gate loop
    k_p_ls: float = 0.0           # coupling coefficient power loop <-> LS gate loop
    k_hs_ls: float = 0.0          # coupling coefficient HS gate loop <-> LS gate loop
    ploop_netlist: str | None = None  # replaces 'Lloop vc dh' + 'Rloop dh dh2' (must connect vc -> dh2 and contain Lloop)


def bench_deck(b: Bench) -> str:
    if b.device == "EPC2015C":
        dn, sub = "EPC2015C_DS", epc_model.subckt("EPC2015C_DS", coss_scale=b.coss_scale)
    else:
        import devices
        dn, sub = devices.subckt(b.device, coss_scale=b.coss_scale)
    lgh = b.L_gate if b.L_gate_hs is None else b.L_gate_hs
    lgl = b.L_gate if b.L_gate_ls is None else b.L_gate_ls
    ploop = b.ploop_netlist or f"Lloop vc dh {b.L_loop}\nRloop dh dh2 {b.R_loop}"
    kl = "".join(f"{n} {a} {c} {k:.6g}\n" for n, a, c, k in (("Kph", "Lloop", "LGH", b.k_p_hs),
                                                               ("Kpl", "Lloop", "LGL", b.k_p_ls),
                                                               ("Kgg", "LGH", "LGL", b.k_hs_ls)) if k != 0.0)
    probes = " v(xsr.gi) v(xhs.gi,sw)" if (b.device != "EPC2015C" or kl or b.L_gate_hs is not None
                                           or b.L_gate_ls is not None or b.ploop_netlist) else ""
    t1 = 5e-9
    t2 = t1 + b.dead
    return f"""* half-bridge hard-commutation bench (generated by scripts/spice_sim.py)
{sub}
VIN vsup 0 {b.vin}
Lb vsup vb {b.L_bulk}
Cb vb 0 {b.C_bulk}
Rbl vb vc 1m
Ccin vc ce {b.C_cin}
Resr ce 0 {b.esr_cin}
{ploop}
XHS dh2 gh sw {dn}
XSR sw gl 0 {dn}
Iload sw 0 {b.iload}
* gate drivers: ideal source -> Rdrive -> Lgate ; separate pull-up/down via diodes-free switch of R
VGH ghd_s sw PULSE(0 {b.v_drive} {t2} {b.t_rise_drv} {b.t_rise_drv} 1 2)
BRH ghd_s ghi I = V(ghd_s,ghi)*(1/{b.r_pulldown} + (1/{b.r_pullup}-1/{b.r_pulldown})*0.5*(1+tanh(V(ghd_s,ghi)/0.02)))
LGH ghi gh {lgh}
VGL gld_s 0 PULSE({b.v_drive} 0 {t1} {b.t_rise_drv} {b.t_rise_drv} 1 2)
BRL gld_s gli I = V(gld_s,gli)*(1/{b.r_pulldown} + (1/{b.r_pullup}-1/{b.r_pulldown})*0.5*(1+tanh(V(gld_s,gli)/0.02)))
LGL gli gl {lgl}
{kl}.options rshunt=1e9 gmin=1e-10 method=gear maxord=2 reltol=1e-4 abstol=1e-9 vntol=1e-6 itl4=200
.tran {b.t_step} {b.t_stop} 0 {b.t_step}
.control
run
wrdata out.txt v(sw) i(Lloop) v(gh,sw) v(gl) v(vc){probes}
.endc
.end
"""


def run_bench(b: Bench, workdir=None) -> dict:
    r = run_deck(bench_deck(b), workdir)
    raw = r["raw"]
    t = raw[:, 0]
    vsw = raw[:, 1]
    il = raw[:, 3]
    out = dict(asdict(b), **metrics(t, vsw, il, b.vin, 5e-9 + b.dead), t=t, vsw=vsw, il=il)
    if raw.shape[1] >= 14:
        t_on = 5e-9 + b.dead
        m = t >= t_on
        vgl = raw[:, 11]
        out.update(vgs_ls_int=vgl, vgs_hs_int=raw[:, 13],
                   vgs_ls_peak=float(np.max(vgl[m])), vgs_ls_min=float(np.min(vgl[m])))
    return out


def _cross(t, y, level, start=0):
    """First time index >= start where y crosses `level` upward (linear interp)."""
    idx = np.nonzero((y[start:-1] < level) & (y[start + 1:] >= level))[0]
    if len(idx) == 0:
        return np.nan, None
    i = idx[0] + start
    tc = t[i] + (level - y[i]) * (t[i + 1] - t[i]) / (y[i + 1] - y[i])
    return tc, i


def metrics(t, vsw, il, vin, t_on):
    """Switch-node metrics after HS turn-on at t_on (robust to slow edges)."""
    i0 = int(np.searchsorted(t, t_on))
    t10, i10 = _cross(t, vsw, 0.1 * vin, i0)
    t90, i90 = _cross(t, vsw, 0.9 * vin, i0)
    dvdt = 0.8 * vin / (t90 - t10) if np.isfinite(t10) and np.isfinite(t90) else np.nan
    # first peak after the 90 % crossing: maximum before the first return to VIN
    out = dict(dvdt_V_per_ns=dvdt * 1e-9, overshoot_pct=np.nan, v_peak=np.nan, f_ring=np.nan, q_ring=np.nan,
               didt_A_per_ns=np.nan)
    if i90 is None:
        return out
    y = vsw[i90:] - vin
    tt = t[i90:]
    down = np.nonzero((y[:-1] >= 0) & (y[1:] < 0))[0]
    j_end = down[0] + 1 if len(down) else len(y)
    k = int(np.argmax(y[:j_end]))
    out["v_peak"] = vin + y[k]
    out["overshoot_pct"] = 100 * y[k] / vin
    # ring frequency & Q from successive maxima of (vsw - VIN)
    from scipy.signal import find_peaks
    pk, _ = find_peaks(y, prominence=0.02 * vin)
    if len(pk) >= 3:
        tp = tt[pk[:5]]
        out["f_ring"] = 1.0 / np.mean(np.diff(tp))
        a = y[pk[:5]]
        a = a[a > 0]
        if len(a) >= 2:
            dec = np.mean(np.log(a[:-1] / a[1:]))          # log decrement per cycle
            out["q_ring"] = np.pi / dec if dec > 0 else np.inf
    # di/dt: max slope of loop current between turn-on and the 90 % point
    seg = slice(i0, i90 + 1)
    if i90 > i0 + 2:
        out["didt_A_per_ns"] = float(np.max(np.gradient(il[seg], t[seg]))) * 1e-9
    return out


def model_check(workdir=None) -> dict:
    """DC transfer at Vds=3 V, RDS(on) at Vgs=5 V, and small-signal Coss(V)."""
    sub = epc_model.subckt()
    deck = f"""* model check
{sub}
VD d 0 3
VG g 0 0
X1 d g 0 EPC2015C_DS
.control
dc VG 0 5 0.05
wrdata out.txt -i(VD)
.endc
.end
"""
    tr = run_deck(deck, workdir)["raw"]
    deck2 = deck.replace("VD d 0 3", "VD d 0 0.1").replace("VG g 0 0", "VG g 0 5").replace(
        "dc VG 0 5 0.05", "op")
    deck2 = deck2.replace("wrdata out.txt -i(VD)", "print -i(VD)\nwrdata out.txt -i(VD)")
    ron = run_deck(deck2, None)["raw"]
    # Coss(V): AC at several DC biases, Vgs=0, C = Im(I)/(w V)
    # Large-signal Coss(V): linear ramp 0 -> 40 V in 400 ns with Vgs = 0,
    # C(V) = I / (dV/dt).  (B-source ddt() is not linearised by ngspice .ac.)
    d3 = f"""* coss ramp
{sub}
VD d 0 PWL(0 0 400n 40)
VG g 0 0
X1 d g 0 EPC2015C_DS
.control
tran 0.5n 400n
let idd = -i(VD)
wrdata out.txt v(d) idd
.endc
.end
"""
    a = run_deck(d3, None)["raw"]
    v = a[:, 1]
    c = a[:, 3] / (40 / 400e-9) * 1e12
    cs = np.array([(vv, float(np.interp(vv, v, c))) for vv in [1, 5, 10, 15, 20, 25, 30, 35, 39]])
    return dict(transfer=tr, ron_current=ron, coss=cs)
