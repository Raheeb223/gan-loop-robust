"""Solver-neutral conductor geometry and exporters.

A geometry is a list of rectangular copper *bars*: each bar runs straight between
two named nodes, has a width (with an explicit width direction) and a thickness.
The same object is exported to
  * FastHenry .inp  (magneto-quasi-static PEEC, filament discretisation), and
  * openEMS / CSXCAD boxes (full-wave FDTD), see oems.py.
That guarantees both solvers see *identical* copper.

Units: millimetres throughout (FastHenry `.units mm`, openEMS unit 1e-3).
Coordinates: x, y in-plane, z up.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

SIGMA_CU_PER_MM = 5.8e4  # S/mm (5.8e7 S/m), annealed copper at 20 C


@dataclass
class Bar:
    n1: str
    n2: str
    w: float                       # width, mm
    h: float                       # thickness, mm
    wdir: tuple[float, float, float] | None = None  # width direction; None = FastHenry default
    nw: int | None = None          # filaments across width (override)
    nh: int | None = None          # filaments across thickness (override)


@dataclass
class Plane:
    """Rectangular copper region on one layer (FastHenry uniform ground plane).

    Contact nodes (named) are snapped by FastHenry to the plane grid; each is
    tied to a regular geometry node of the same name via .equiv.
    """
    name: str
    x0: float
    y0: float
    x1: float
    y1: float
    z: float
    thick: float
    pitch: float = 0.2
    contacts: list[str] = field(default_factory=list)


@dataclass
class Geometry:
    name: str
    nodes: dict[str, tuple[float, float, float]] = field(default_factory=dict)
    bars: list[Bar] = field(default_factory=list)
    planes: list[Plane] = field(default_factory=list)
    ports: list[tuple[str, str]] = field(default_factory=list)  # (+, -) node pairs
    equivs: list[list[str]] = field(default_factory=list)        # ideal shorts (port bundling)
    port_box: tuple | None = None   # openEMS: (start xyz, stop xyz, axis 'x'|'y'|'z')
    notes: str = ""

    def plane(self, name, x0, y0, x1, y1, z, thick, pitch=0.2) -> Plane:
        p = Plane(name, min(x0, x1), min(y0, y1), max(x0, x1), max(y0, y1), z, thick, pitch)
        self.planes.append(p)
        return p

    def contact(self, plane: Plane, name: str, x: float, y: float) -> str:
        """Create a node on `plane` at (x, y); bars may then connect to it."""
        assert plane.x0 - 1e-9 <= x <= plane.x1 + 1e-9 and plane.y0 - 1e-9 <= y <= plane.y1 + 1e-9, \
            f"contact {name} ({x},{y}) outside plane {plane.name}"
        self.node(name, x, y, plane.z)
        plane.contacts.append(name)
        return name

    def node(self, name: str, x: float, y: float, z: float) -> str:
        self.nodes[name] = (float(x), float(y), float(z))
        return name

    def bar(self, n1, n2, w, h, wdir=None, nw=None, nh=None):
        self.bars.append(Bar(n1, n2, w, h, wdir, nw, nh))

    # ------------------------------------------------------------------ boxes
    def boxes(self):
        """Axis-aligned bounding boxes (start, stop) of every bar, for openEMS.

        Only axis-aligned bars are supported (all PCB geometry here is).
        """
        out = []
        for b in self.bars:
            p1 = np.array(self.nodes[b.n1])
            p2 = np.array(self.nodes[b.n2])
            d = p2 - p1
            L = np.linalg.norm(d)
            ax = int(np.argmax(np.abs(d)))
            assert np.isclose(abs(d[ax]), L), f"bar {b.n1}-{b.n2} is not axis-aligned"
            wv = np.array(b.wdir if b.wdir is not None else _default_wdir(d), float)
            wv /= np.linalg.norm(wv)
            hv = np.cross(d / L, wv)
            lo = np.minimum(p1, p2) - np.abs(wv) * b.w / 2 - np.abs(hv) * b.h / 2
            hi = np.maximum(p1, p2) + np.abs(wv) * b.w / 2 + np.abs(hv) * b.h / 2
            out.append((lo, hi))
        return out


def _default_wdir(d):
    """FastHenry default width direction: in the x-y plane, perpendicular to the segment."""
    d = np.asarray(d, float)
    if abs(d[0]) < 1e-12 and abs(d[1]) < 1e-12:
        raise ValueError("vertical bar needs explicit wdir")
    v = np.array([-d[1], d[0], 0.0])
    return v / np.linalg.norm(v)


def to_fasthenry(g: Geometry, freqs=(1e6,), *, ndec: float = 1, max_fil_w: float = 0.25, nh: int = 1,
                 ratio: float = 2.0, sigma: float = SIGMA_CU_PER_MM, title: str | None = None) -> str:
    """Export a Geometry to FastHenry input text.

    Width discretisation: nwinc = ceil(w / max_fil_w), geometric ratio `ratio`
    (FastHenry's rw) to refine filaments toward edges, where current crowds.
    """
    lines = [f"* {title or g.name}", "* generated by scripts/geom.py", ".units mm",
             f".default sigma={sigma:g}"]
    for p in g.planes:
        s1 = max(1, int(round((p.x1 - p.x0) / p.pitch)))
        s2 = max(1, int(round((p.y1 - p.y0) / p.pitch)))
        lines += [f"g{p.name} x1={p.x0:.6g} y1={p.y0:.6g} z1={p.z:.6g}",
                  f"+ x2={p.x1:.6g} y2={p.y0:.6g} z2={p.z:.6g}",
                  f"+ x3={p.x1:.6g} y3={p.y1:.6g} z3={p.z:.6g}",
                  f"+ thick={p.thick:.6g} seg1={s1} seg2={s2} sigma={sigma:g} nhinc={nh}"]
        for c in p.contacts:
            x, y, z = g.nodes[c]
            lines.append(f"+ nP{c} ({x:.6g},{y:.6g},{z:.6g})")
    for name, (x, y, z) in g.nodes.items():
        lines.append(f"N{name} x={x:.6g} y={y:.6g} z={z:.6g}")
    for p in g.planes:
        for c in p.contacts:
            lines.append(f".equiv N{c} nP{c}")
    for grp in g.equivs:
        lines.append(".equiv " + " ".join(f"N{n}" for n in grp))
    for i, b in enumerate(g.bars):
        nw = b.nw or max(1, int(np.ceil(b.w / max_fil_w)))
        nhh = b.nh or nh
        s = f"E{i} N{b.n1} N{b.n2} w={b.w:.6g} h={b.h:.6g} nwinc={nw} nhinc={nhh}"
        if nw > 1:
            s += f" rw={ratio:g}"
        if nhh > 1:
            s += f" rh={ratio:g}"
        if b.wdir is not None:
            s += " wx={:.6g} wy={:.6g} wz={:.6g}".format(*b.wdir)
        lines.append(s)
    for p, m in g.ports:
        lines.append(f".external N{p} N{m}")
    # FastHenry only supports a log sweep; we always sweep min..max with `ndec`
    # points per decade (default 1 => every decade), so decade frequencies are exact.
    fs = sorted(freqs)
    lines.append(f".freq fmin={fs[0]:g} fmax={fs[-1]:g} ndec={ndec:g}")
    lines.append(".end")
    return "\n".join(lines) + "\n"


