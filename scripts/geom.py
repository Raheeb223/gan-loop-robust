def two_plate_loop(w: float, l: float, e: float, h: float = 0.035, *, ret_w: float | None = None,
                   name: str = "two_plate") -> Geometry:
    """Top conductor over a return conductor, shorted at x = l, port at x = 0.

    `e` is the dielectric gap between facing copper surfaces (as in Letellier 2018).
    The end short is a full-width vertical copper wall (models their solder-filled
    slot).  The port is a full-width vertical "gap" at x = 0: to keep the port
    itself free of extra inductance we feed it with an ideal full-width strip of
    nodes, i.e. the .external is between the two plate *end* nodes and FastHenry's
    segment model already spreads current across the plate width.
    """
    g = Geometry(name, notes=f"w={w} l={l} e={e} h={h} (mm)")
    zt = e / 2 + h / 2
    zb = -zt
    g.node("t0", 0, 0, zt); g.node("t1", l, 0, zt)
    g.node("b0", 0, 0, zb); g.node("b1", l, 0, zb)
    g.bar("t0", "t1", w, h)
    g.bar("b0", "b1", ret_w or w, h)
    # end short: vertical wall, width along y, thickness h along x
    g.bar("t1", "b1", w, h, wdir=(0, 1, 0))
    g.ports.append(("t0", "b0"))
    return g


def straight_bar(l: float, w: float, h: float) -> Geometry:
    g = Geometry("bar")
    g.node("a", 0, 0, 0); g.node("b", l, 0, 0)
    g.bar("a", "b", w, h)
    g.ports.append(("a", "b"))
    return g
